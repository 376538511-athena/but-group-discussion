-- 2. 请假申请表
CREATE TABLE IF NOT EXISTS public.leave_requests (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  week_start  date NOT NULL,           -- Thursday of the week being requested
  reason      text NOT NULL,
  status      text NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending', 'approved', 'rejected')),
  admin_id    uuid REFERENCES public.profiles(id),
  admin_note  text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS leave_requests_user_week_uidx
  ON public.leave_requests (user_id, week_start);

DROP TRIGGER IF EXISTS set_leave_requests_updated_at ON public.leave_requests;
CREATE TRIGGER set_leave_requests_updated_at
  BEFORE UPDATE ON public.leave_requests
  FOR EACH ROW EXECUTE PROCEDURE public.set_updated_at();

-- 3. 通知表
CREATE TABLE IF NOT EXISTS public.notifications (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id   uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  title     text NOT NULL,
  content   text NOT NULL,
  is_read   boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 4. 文献收藏表
CREATE TABLE IF NOT EXISTS public.paper_bookmarks (
  paper_id   bigint NOT NULL REFERENCES public.papers(id) ON DELETE CASCADE,
  user_id    uuid   NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (paper_id, user_id)
);

-- 5. 评论收藏表
CREATE TABLE IF NOT EXISTS public.comment_bookmarks (
  comment_id bigint NOT NULL REFERENCES public.comments(id) ON DELETE CASCADE,
  user_id    uuid   NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (comment_id, user_id)
);

