-- leave_requests
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "users can read own leave requests" ON public.leave_requests;
CREATE POLICY "users can read own leave requests"
  ON public.leave_requests FOR SELECT TO authenticated
  USING (auth.uid() = user_id OR EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'
  ));

DROP POLICY IF EXISTS "users can insert own leave request" ON public.leave_requests;
CREATE POLICY "users can insert own leave request"
  ON public.leave_requests FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "admins can update leave requests" ON public.leave_requests;
CREATE POLICY "admins can update leave requests"
  ON public.leave_requests FOR UPDATE TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'
  ))
  WITH CHECK (EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'
  ));

DROP POLICY IF EXISTS "users can delete own pending leave" ON public.leave_requests;
CREATE POLICY "users can delete own pending leave"
  ON public.leave_requests FOR DELETE TO authenticated
  USING (auth.uid() = user_id AND status = 'pending');

